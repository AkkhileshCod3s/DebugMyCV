import rateLimit from 'express-rate-limit';

const message = (seconds) => `Too many requests. Please try again in about ${seconds} seconds.`;

export const generalLimiter = rateLimit({
  windowMs: 15 * 60 * 1000,
  limit: 600,
  standardHeaders: 'draft-7',
  legacyHeaders: false,
  message: { success: false, message: message(900) },
});

